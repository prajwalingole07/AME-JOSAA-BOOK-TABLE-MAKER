def clean_key(name):
    """Normalize string for fuzzy comparison."""
    if not name:
        return ""
    return re.sub(r"[^a-zA-Z0-9]", "", str(name).lower())


_INDEX = {clean_key(k): v for k, v in INSTITUTE_METADATA.items()}


def get_institute_metadata(institute_name):
    """
    Lookup official metadata for an institute.
    Returns dict with keys: name_full, type, established, state, address,
    phone, web, email, fees, total_intake.
    """
    if not institute_name:
        return _fallback_metadata(institute_name)

    if institute_name in INSTITUTE_METADATA:
        meta = INSTITUTE_METADATA[institute_name].copy()
        meta["name_full"] = institute_name
        return meta

    ck = clean_key(institute_name)
    if ck in _INDEX:
        meta = _INDEX[ck].copy()
        meta["name_full"] = institute_name
        return meta

    for k, v in INSTITUTE_METADATA.items():
        ck_target = clean_key(k)
        if ck and ck_target and (ck in ck_target or ck_target in ck):
            meta = v.copy()
            meta["name_full"] = institute_name
            return meta

    return _fallback_metadata(institute_name)


def _fallback_metadata(name):
    low = str(name).lower()
    if "indian institute of technology" in low:
        inst_type = "IIT"
    elif "national institute of technology" in low:
        inst_type = "NIT"
    elif "information" in low or "international institute" in low:
        inst_type = "IIIT"
    else:
        inst_type = "GFTI"
    return {
        "name_full": str(name) if name else "Institute",
        "type": inst_type,
        "established": "----",
        "state": "----",
        "address": str(name),
        "phone": "----",
        "web": "----",
        "email": "----",
        "fees": "----",
        "total_intake": "----",
    }
